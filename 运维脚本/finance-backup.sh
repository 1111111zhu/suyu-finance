#!/usr/bin/env bash
# Consistent databases + files: short website downtime; no live restore.
set +x
set -Eeuo pipefail
umask 077
root=${1:?Absolute private backup directory required}
[[ $root == /* && $root != / && $root != *'/../'* && ! -L $root ]] || exit 1
compose=(docker compose -f compose.finance.yaml)
install -d -m 700 "$root"
out=$(mktemp -d "$root/finance-$(date -u +%Y%m%dT%H%M%SZ)-XXXXXXXX")
printf 'incomplete\n' >"$out/status"
"${compose[@]}" stop web >/dev/null
trap '"${compose[@]}" start web >/dev/null' EXIT
for kind in rd payroll; do
  "${compose[@]}" exec -T postgres bash -c '
    export PGPASSWORD="$POSTGRES_PASSWORD"
    if [[ $1 == rd ]]; then db=$RD_DB_NAME; else db=$PAYROLL_DB_NAME; fi
    exec pg_dump -h 127.0.0.1 -U "$POSTGRES_USER" -d "$db" -Fc --no-password
  ' -- "$kind" >"$out/$kind.dump"
  "${compose[@]}" exec -T postgres pg_restore --list <"$out/$kind.dump" >"$out/$kind.contents"
done
# One-off maintenance container mounts the exact existing files volume; no port.
"${compose[@]}" run --rm --no-deps -T --entrypoint tar web -C /app/storage -czf - . >"$out/files.tar.gz"
tar -tzf "$out/files.tar.gz" >/dev/null
(cd "$out" && sha256sum rd.dump payroll.dump files.tar.gz >SHA256SUMS)
printf 'complete\n' >"$out/status"
# Only completed backups generated by this script are eligible for retention.
while IFS= read -r -d '' dir; do
  [[ -f $dir/status && $(<"$dir/status") == complete ]] && rm -rf -- "$dir"
done < <(find "$root" -mindepth 1 -maxdepth 1 -type d -name 'finance-*' -mtime +29 -print0)
printf '%s\n' "$out"
