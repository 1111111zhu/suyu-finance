import fs from 'node:fs';

const root = new URL('../public/salary/', import.meta.url);
// Keep one authoritative implementation of the existing salary rules. The worker
// copy has no DOM bootstrap; rendering functions are defined but never invoked.
export function workerModel(html) {
  const inline = html.match(/<script>\s*([\s\S]*?)<\/script>/)?.[1];
  if (!inline) throw new Error('Missing payroll application model');
  const end = inline.lastIndexOf("    document.querySelectorAll('.nav')");
  if (end < 0) throw new Error('Missing payroll DOM bootstrap boundary');
  return '// Generated by build-payroll-worker-model.mjs; edit index.html instead.\n' + inline.slice(0, end)
    .replace(/    if \(typeof window[^\n]+document\.documentElement[^\n]+\n/, '')
    .replace(/const (content|crumbBatch|toastEl) = document\.getElementById\('[^']+'\);/g, 'const $1 = null;');
}

const generated = workerModel(fs.readFileSync(new URL('index.html', root), 'utf8'));
if (process.argv.includes('--check')) {
  if (fs.readFileSync(new URL('calculation-model.js', root), 'utf8') !== generated)
    throw new Error('Payroll worker model is stale: run node 自动化脚本/build-payroll-worker-model.mjs');
} else {
  fs.writeFileSync(new URL('calculation-model.js', root), generated);
}
